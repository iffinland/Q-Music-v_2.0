import DOMPurify from 'dompurify';
import { jsonBase64 } from '../services/publishing/content';
export const objectToBase64 = async (value: unknown) => jsonBase64(value);
export const sanitizedContent = (html: string) =>
  DOMPurify.sanitize(html, {
    ALLOWED_TAGS: [
      'a',
      'b',
      'i',
      'em',
      'strong',
      'p',
      'br',
      'div',
      'span',
      'img',
      'ul',
      'ol',
      'li',
      'h1',
      'h2',
      'h3',
      'h4',
      'h5',
      'h6',
      'blockquote',
      'code',
      'pre',
      'table',
      'thead',
      'tbody',
      'tr',
      'th',
      'td',
      's',
      'hr',
    ],
    ALLOWED_ATTR: [
      'href',
      'target',
      'rel',
      'class',
      'src',
      'alt',
      'title',
      'width',
      'height',
      'style',
      'align',
      'valign',
      'colspan',
      'rowspan',
      'border',
      'cellpadding',
      'cellspacing',
      'data-url',
    ],
  }).replace(
    /<span[^>]*data-url="qortal:\/\/use-embed\/[^"]*"[^>]*>.*?<\/span>/g,
    ''
  );
